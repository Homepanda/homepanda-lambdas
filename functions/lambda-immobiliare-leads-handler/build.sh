#!/usr/bin/env bash
# Ricetta del solo immobiliare-leads-handler.
# Node 24.11.0 è il pin di build di questa funzione, non la patch del runtime Lambda.
set -euo pipefail

: "${FUNCTION_LOGICAL_NAME:?}"
: "${FUNCTION_NAME:?}"
: "${FUNCTION_DIR:?}"
: "${FUNCTION_RUNTIME:?}"
: "${FUNCTION_ARCH:?}"
: "${FUNCTION_PACKAGE_TYPE:?}"
: "${FUNCTION_ACCOUNT_ID:?}"
: "${FUNCTION_REGION:?}"
: "${FUNCTION_SOURCE_ROOT:?}"
: "${FUNCTION_STRATEGY:?}"
: "${FUNCTION_ARTIFACT:?}"
: "${NODE_VERSION:?}"
: "${YARN_VERSION:?}"
: "${DIST_DIR:?}"

if [[ "$FUNCTION_LOGICAL_NAME" != "immobiliare-leads-handler" \
  || "$FUNCTION_NAME" != "lambda-immobiliare-leads-handler" \
  || "$FUNCTION_RUNTIME" != "nodejs24.x" \
  || "$FUNCTION_ARCH" != "x86_64" \
  || "$FUNCTION_PACKAGE_TYPE" != "Zip" \
  || "$FUNCTION_ACCOUNT_ID" != "247981707334" \
  || "$FUNCTION_REGION" != "eu-central-1" \
  || "$FUNCTION_STRATEGY" != "nodejs-zip-yarn-classic" \
  || "$FUNCTION_ARTIFACT" != "immobiliare-leads-handler.zip" \
  || "$NODE_VERSION" != "24.11.0" \
  || "$YARN_VERSION" != "1.22.22" ]]; then
  echo "Questa ricetta è solo per immobiliare-leads-handler." >&2
  exit 1
fi

if [[ "$(uname -m)" != "x86_64" ]]; then
  echo "Il progetto x86_64 rifiuta un host diverso da x86_64." >&2
  exit 1
fi

for tool in curl tar zip sha256sum python3; do
  command -v "$tool" >/dev/null
done

src=$FUNCTION_SOURCE_ROOT
for relative in \
  index.mjs \
  package.json \
  yarn.lock \
  services/homepanda.mjs \
  services/immobiliare.mjs
do
  if [[ ! -f "$src/$relative" ]]; then
    echo "File sorgente mancante: $relative" >&2
    exit 1
  fi
done

source_fingerprint() {
  find "$1" -type f ! -path '*/node_modules/*' -printf '%P\n' | sort | while IFS= read -r relative; do
    sha256sum "$1/$relative"
  done | sha256sum | awk '{print $1}'
}

before_sources=$(source_fingerprint "$src")

toolchain=$(mktemp -d /tmp/hp-toolchain.XXXXXX)
stage=$(mktemp -d /tmp/hp-lambda-stage.XXXXXX)
cleanup() {
  rm -rf "$toolchain" "$stage"
}
trap cleanup EXIT

mkdir -p "$stage/services"
cp -a "$src/index.mjs" "$src/package.json" "$src/yarn.lock" "$stage/"
cp -a "$src/services/." "$stage/services/"

lock_line_1=$(sed -n '1p' "$stage/yarn.lock")
lock_line_2=$(sed -n '2p' "$stage/yarn.lock")
if [[ "$lock_line_1" != "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY." \
  || "$lock_line_2" != "# yarn lockfile v1" ]]; then
  echo "yarn.lock non è Yarn Classic v1. Dipendenze non installate." >&2
  exit 1
fi
if grep -q '"packageManager"[[:space:]]*:[[:space:]]*"yarn@[234]' "$stage/package.json"; then
  echo "package.json non è Yarn Classic. Dipendenze non installate." >&2
  exit 1
fi

NODE_SHA256=b3c071cdf47aab867c3b2aa287257df12ec5d7c962bf922b32fd33226c4295fd
NODE_URL="https://nodejs.org/dist/v${NODE_VERSION}/node-v${NODE_VERSION}-linux-x64.tar.gz"
YARN_URL="https://registry.npmjs.org/yarn/-/yarn-${YARN_VERSION}.tgz"
YARN_SHA512=prL3kGtyG7o9Z9Sv8IPfBNrWTDmXB4Qbes8A9rEzt6wkJV8mUvoirjU0Mp3GGAU06Y0XQyA3/2/RQFVuK7MTfg==

download() {
  local url=$1
  local destination=$2
  if ! curl --fail --show-error --location \
    --connect-timeout 20 --max-time 180 \
    --retry 2 --retry-connrefused \
    --output "$destination" \
    "$url"; then
    echo "Download HTTP fallito: $url" >&2
    exit 1
  fi
}

download "$NODE_URL" "$toolchain/node.tar.gz"
actual_node_sha=$(sha256sum "$toolchain/node.tar.gz" | awk '{print $1}')
if [[ "$actual_node_sha" != "$NODE_SHA256" ]]; then
  echo "Checksum SHA-256 di Node non valido. Archivio non estratto." >&2
  exit 1
fi
mkdir -p "$toolchain/node"
tar -xzf "$toolchain/node.tar.gz" -C "$toolchain/node"

node_bin="$toolchain/node/node-v${NODE_VERSION}-linux-x64/bin/node"
npm_cli="$toolchain/node/node-v${NODE_VERSION}-linux-x64/bin/npm"
if [[ ! -x "$node_bin" || ! -f "$npm_cli" ]]; then
  echo "Distribuzione Node incompleta dopo l'estrazione." >&2
  exit 1
fi

node_version=$("$node_bin" --version)
npm_version=$("$node_bin" "$npm_cli" --version)
if [[ "$node_version" != "v${NODE_VERSION}" || -z "$npm_version" ]]; then
  echo "Versione Node o npm inattesa: node=${node_version} npm=${npm_version}" >&2
  exit 1
fi
echo "Toolchain: node ${node_version}, npm ${npm_version}"

download "$YARN_URL" "$toolchain/yarn.tgz"
if ! python3 - "$toolchain/yarn.tgz" "$YARN_SHA512" << 'PY'
import base64
import hashlib
import pathlib
import sys

payload = pathlib.Path(sys.argv[1]).read_bytes()
expected = sys.argv[2]
actual = base64.b64encode(hashlib.sha512(payload).digest()).decode()
if actual != expected:
    sys.stderr.write("Checksum di Yarn non valido. Archivio non estratto.\n")
    sys.exit(1)
PY
then
  exit 1
fi
mkdir -p "$toolchain/yarn"
tar -xzf "$toolchain/yarn.tgz" -C "$toolchain/yarn"
yarn_js=$toolchain/yarn/package/bin/yarn.js
if [[ ! -f "$yarn_js" ]]; then
  echo "Distribuzione Yarn incompleta dopo l'estrazione." >&2
  exit 1
fi
yarn_version=$("$node_bin" "$yarn_js" --version)
if [[ "$yarn_version" != "$YARN_VERSION" ]]; then
  echo "Versione Yarn inattesa: ${yarn_version}" >&2
  exit 1
fi

(
  cd "$stage"
  YARN_CACHE_FOLDER="$toolchain/yarn-cache" \
    "$node_bin" "$yarn_js" install \
    --frozen-lockfile \
    --production=true \
    --non-interactive \
    --network-timeout 120000
)

echo "Controllo sintattico con node --check. Non è un test funzionale."
while IFS= read -r file; do
  "$node_bin" --check "$file"
done < <(find "$stage" -name '*.mjs' -not -path '*/node_modules/*' | sort)

python3 - "$stage" << 'PY'
import json
import sys
from pathlib import Path

stage = Path(sys.argv[1])
package = json.loads((stage / "package.json").read_text(encoding="utf-8"))
missing = []
for name in package.get("dependencies", {}):
    if not (stage / "node_modules" / name / "package.json").is_file():
        missing.append(name)
if missing:
    sys.stderr.write("Dipendenze assenti nello staging: " + ", ".join(missing) + "\n")
    sys.exit(1)
PY

(
  cd "$stage"
  zip -qr -X "$toolchain/package.zip" . -x '*.DS_Store'
)

python3 - "$toolchain/package.zip" << 'PY'
import sys
import zipfile

archive = zipfile.ZipFile(sys.argv[1])
names = archive.namelist()
required = [
    "index.mjs",
    "package.json",
    "yarn.lock",
    "services/homepanda.mjs",
    "services/immobiliare.mjs",
    "node_modules/axios/package.json",
    "node_modules/axios-cookiejar-support/package.json",
    "node_modules/cheerio/package.json",
    "node_modules/tough-cookie/package.json",
]
missing = [name for name in required if name not in names]
prefixed = [name for name in names if name == "src" or name.startswith("src/")]
allowed_top = {"index.mjs", "package.json", "yarn.lock", "services", "node_modules"}
unexpected = sorted({
    name.split("/", 1)[0]
    for name in names
    if name.split("/", 1)[0] not in allowed_top
})
if missing or prefixed or unexpected:
    sys.stderr.write(
        "Pacchetto non valido. "
        f"mancanti={missing} prefisso_src={prefixed} inattesi={unexpected}\n"
    )
    sys.exit(1)
PY

mkdir -p "$DIST_DIR/manifests"
rm -f "$DIST_DIR/$FUNCTION_ARTIFACT"
mv "$toolchain/package.zip" "$DIST_DIR/$FUNCTION_ARTIFACT"
zip_sha=$(sha256sum "$DIST_DIR/$FUNCTION_ARTIFACT" | awk '{print $1}')

if [[ -n "${CODEBUILD_RESOLVED_SOURCE_VERSION:-}" ]]; then
  release_commit=$CODEBUILD_RESOLVED_SOURCE_VERSION
elif release_commit=$(git -C "$FUNCTION_DIR" rev-parse --verify HEAD 2>/dev/null); then
  :
else
  release_commit=
fi

RELEASE_COMMIT=$release_commit \
RELEASE_NPM_VERSION=$npm_version \
RELEASE_ZIP_SHA256=$zip_sha \
python3 - << 'PY'
import json
import os
from pathlib import Path

commit = os.environ.get("RELEASE_COMMIT") or None
manifest = {
    "logicalName": os.environ["FUNCTION_LOGICAL_NAME"],
    "functionName": os.environ["FUNCTION_NAME"],
    "accountId": os.environ["FUNCTION_ACCOUNT_ID"],
    "region": os.environ["FUNCTION_REGION"],
    "packageType": os.environ["FUNCTION_PACKAGE_TYPE"],
    "handler": "index.handler",
    "commit": commit,
    "runtime": os.environ["FUNCTION_RUNTIME"],
    "architecture": os.environ["FUNCTION_ARCH"],
    "toolchain": {
        "node": os.environ["NODE_VERSION"],
        "npm": os.environ["RELEASE_NPM_VERSION"],
        "yarn": os.environ["YARN_VERSION"],
        "pinScope": "function",
    },
    "zipFile": os.environ["FUNCTION_ARTIFACT"],
    "zipSha256": os.environ["RELEASE_ZIP_SHA256"],
    "syntaxCheck": {
        "performed": True,
        "functionalTest": False,
    },
}
destination = Path(os.environ["DIST_DIR"]) / "manifests" / (os.environ["FUNCTION_LOGICAL_NAME"] + ".json")
destination.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
PY

after_sources=$(source_fingerprint "$src")
if [[ "$before_sources" != "$after_sources" ]]; then
  echo "I sorgenti sono stati modificati durante la build." >&2
  exit 1
fi

echo "Pacchetto: $DIST_DIR/$FUNCTION_ARTIFACT"
echo "SHA-256: $zip_sha"
